public class Buch {
    String titel;
    String autor;
    int preis;
    int anzahlSeiten;

    public Buch(String titel, String autor, int preis, int anzahlSeiten) {
        this.titel = titel;
        this.autor = autor;
        this.preis = preis;
        this.anzahlSeiten = anzahlSeiten;
    }
}
